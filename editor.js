(function(){
'use strict';
var existing=Array.isArray(window.NEIL_REPORTS)?window.NEIL_REPORTS:[];
function get(id){return document.getElementById(id)}
var names=['date','category','title','subtitle','summary','focus','body','bullets','tags','source','url','sample'];
var f={};names.forEach(function(n){f[n]=get('f-'+n)});
var select=get('edit-existing'),feedback=get('editor-feedback');
f.date.value=new Intl.DateTimeFormat('en-CA',{year:'numeric',month:'2-digit',day:'2-digit',timeZone:'Asia/Taipei'}).format(new Date());
existing.slice().sort(function(a,b){return (b.date||'').localeCompare(a.date||'')}).forEach(function(r){
var o=document.createElement('option');o.value=r.id;o.textContent=(r.date||'')+'｜'+(r.title||'未命名');select.appendChild(o)
});
select.addEventListener('change',function(){
var r=existing.find(function(x){return x.id===select.value});
if(!r){names.forEach(function(n){if(n!=='date'&&n!=='category'&&n!=='sample')f[n].value=''});f.category.value='market';f.sample.value='true';feedback.textContent='已切換至新增文章。';return}
f.date.value=r.date||'';f.category.value=r.category||'market';f.title.value=r.title||'';f.subtitle.value=r.subtitle||'';
f.summary.value=r.summary||'';f.focus.value=r.focus||'';f.body.value=(r.sections||[]).reduce(function(a,s){return a.concat(s.paragraphs||[])},[]).join('\n\n');
f.bullets.value=(r.sections||[]).reduce(function(a,s){return a.concat(s.bullets||[])},[]).join('\n');
f.tags.value=(r.tags||[]).join(', ');f.source.value=r.source||'';f.url.value=r.sourceUrl||'';f.sample.value=String(Boolean(r.sample));
feedback.textContent='已載入原有文章；下載時會用編輯後的正文、條列重建章節，原圖表欄位會清空，請先備份。';
});
function val(n){return String(f[n].value||'').trim()}
function produce(){
if(!val('date')||!val('title')||!val('summary')||!val('body')){feedback.textContent='請填寫日期、標題、摘要與正文。';return null}
if(val('url')&&!/^https?:\/\//i.test(val('url'))){feedback.textContent='來源網址需以 https:// 或 http:// 開頭。';return null}
var prev=existing.find(function(x){return x.id===select.value});
var slug=val('title').toLowerCase().replace(/[^a-z0-9\u3400-\u9fff]+/g,'-').replace(/^-|-$/g,'').slice(0,45);
var id=prev?prev.id:val('category')+'-'+val('date')+'-'+(slug||'report');
var paragraphs=val('body').split(/\n\s*\n/).map(function(x){return x.trim()}).filter(Boolean);
var bullets=val('bullets').split(/\n/).map(function(x){return x.trim()}).filter(Boolean);
var sections=[{heading:'市場重點與分析',paragraphs:paragraphs}];if(bullets.length)sections.push({heading:'關鍵觀察',bullets:bullets});
var report={id:id,title:val('title'),subtitle:val('subtitle'),date:val('date'),category:val('category'),featured:false,sample:val('sample')==='true',readingMinutes:Math.max(2,Math.ceil(val('body').length/350)),summary:val('summary'),focus:val('focus'),tags:val('tags').split(',').map(function(x){return x.trim()}).filter(Boolean),metrics:[],chart:null,sections:sections,source:val('source')||'尚未提供資料來源',sourceUrl:val('url')};
var all=[report].concat(existing.filter(function(x){return x.id!==id}));
return '/* Generated by Neil Financial Desk; verify data and publication rights. */\nwindow.NEIL_REPORTS = '+JSON.stringify(all,null,2)+';\n';
}
get('download-btn').addEventListener('click',function(){
var content=produce();if(!content)return;
var url=URL.createObjectURL(new Blob([content],{type:'text/javascript;charset=utf-8'})),a=document.createElement('a');
a.href=url;a.download='reports.js';document.body.appendChild(a);a.click();a.remove();setTimeout(function(){URL.revokeObjectURL(url)},10000);
feedback.textContent='已下載 reports.js；尚未發布。請在 GitHub 取代同名檔案並提交變更。';
});
get('copy-btn').addEventListener('click',function(){
var content=produce();if(!content)return;
if(navigator.clipboard&&navigator.clipboard.writeText){navigator.clipboard.writeText(content).then(function(){feedback.textContent='已複製。可貼到 GitHub 的 reports.js 編輯頁。'}).catch(function(){feedback.textContent='複製失敗，請使用下載功能。'})}
else{feedback.textContent='瀏覽器不支援複製，請使用下載功能。'}
});
})();